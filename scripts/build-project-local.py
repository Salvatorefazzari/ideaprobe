#!/usr/bin/env python3
"""Build a project-local (cloud-compatible) IdeaProbe bundle.

IdeaProbe ships as a Claude Code *plugin* (skills/, agents/, refs/, hooks/).
Environments without `/plugin` support (e.g. Claude Code on the web / cloud
sessions) cannot install it, and plugin SessionStart hooks never run there.

This script converts the plugin sources into files Claude Code discovers on its
own in any project directory:

    <target>/.claude/skills/<skill>/SKILL.md   project skills (auto-discovered)
    <target>/.claude/agents/<agent>.md         project subagents (auto-discovered)
    <target>/.claude/ideaprobe/refs/*.md       scoring rubric, templates, sources
    <target>/.claude/ideaprobe/manifest.json   version + generated file list
    <target>/CLAUDE.md                         bootstrap block (replaces the hook)

The plugin sources stay the single source of truth; never edit the generated
files by hand. Re-run this script after changing skills/, agents/ or refs/.

Usage:
    python3 scripts/build-project-local.py                  # build into this repo
    python3 scripts/build-project-local.py --target ../app  # install into another project
    python3 scripts/build-project-local.py --check          # exit 1 if bundle is stale
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUNDLE_DIR = ".claude/ideaprobe"
REFS_PREFIX = f"{BUNDLE_DIR}/refs/"
BEGIN = "<!-- ideaprobe:begin (generated by scripts/build-project-local.py; do not edit inside this block) -->"
END = "<!-- ideaprobe:end -->"

# Plugin "model tier" wording -> Agent tool `model` values.
MODEL_TIERS = {
    "sentiment-scanner": "haiku",
    "market-researcher": "sonnet",
    "competitor-scout": "sonnet",
    "validation-reviewer": "opus",
}


def split_frontmatter(text: str) -> tuple[str, str]:
    if not text.startswith("---\n"):
        return "", text
    end = text.index("\n---\n", 4)
    return text[: end + 5], text[end + 5 :]


def transform(text: str, agents: list[str]) -> str:
    """Rewrite plugin-relative references to project-local ones."""
    # refs/x.md -> .claude/ideaprobe/refs/x.md (skip already-rewritten paths)
    text = re.sub(r"(?<![\w/.-])refs/([A-Za-z0-9_-]+\.md)", REFS_PREFIX + r"\1", text)
    # Example dispatch lines: Agent(description="...", prompt="You are ideaprobe:x. ...")
    text = re.sub(
        r'Agent\(description="([^"]*)", prompt="You are ideaprobe:([a-z-]+)\. ',
        r'Agent(subagent_type="\2", description="\1", prompt="',
        text,
    )
    # Namespaced agent names -> project subagent names
    for agent in agents:
        text = text.replace(f"ideaprobe:{agent}", agent)
    text = text.replace(
        "from the IdeaProbe plugin directory",
        "(project-local IdeaProbe bundle, path relative to the project root)",
    )
    text = text.replace("**Plugin template (read-only):**", "**IdeaProbe template (read-only):**")
    text = text.replace("(not in the plugin — it survives updates)", "(outside the generated bundle — it survives rebuilds)")
    return text


def dispatch_note(agents_used: list[str]) -> str:
    rows = "\n".join(
        f"| `{a}` | `.claude/agents/{a}.md` | `{MODEL_TIERS.get(a, 'sonnet')}` |" for a in agents_used
    )
    return f"""

## Project-Local Dispatch (cloud-compatible)

This skill runs from the project-local IdeaProbe bundle, not the plugin. Agents
are project subagents, so dispatch them by `subagent_type` (no `ideaprobe:` prefix):

| Agent | Definition | Suggested `model` |
|-------|-----------|-------------------|
{rows}

Model tiers map to the Agent tool's `model` parameter: fast → `haiku`,
standard → `sonnet`, most capable → `opus` (or omit `model` to use the session's
model). Escalate one tier if results come back thin.

If a `subagent_type` is rejected as unknown (e.g. the session started before
`.claude/agents/` existed), fall back to the `general-purpose` agent and begin
its prompt with: "Read `.claude/agents/<agent>.md` and follow it exactly as your
instructions." followed by the full idea context.

Research agents need web access. If `WebSearch` is listed only as a deferred
tool, load it with ToolSearch first. If no web tool works, report that in
**Data Gaps** and score conservatively — never fill gaps with invented data.
"""


AGENT_WEB_NOTE = """

## Web Access (project-local / cloud sessions)

Use `WebSearch` and `WebFetch` for research. If either is listed only as a
deferred tool, load it with ToolSearch before calling it. If no web tool is
available or every search fails, say so explicitly under **Data Gaps** — never
substitute remembered or invented data for live sources.
"""


def bootstrap_block(router_body: str, version: str) -> str:
    return f"""{BEGIN}
# IdeaProbe (project-local, v{version})

IdeaProbe business-idea validation is installed in this project as plain
Claude Code files — no `/plugin` command or plugin hook is needed:

- Skills: `.claude/skills/` (invoke with the Skill tool or `/idea-validation`, `/idea-comparison`, …)
- Research agents: `.claude/agents/` (`market-researcher`, `competitor-scout`, `sentiment-scanner`, `validation-reviewer`)
- Scoring rubric, templates, data sources: `.claude/ideaprobe/refs/`
- Founder profile (user data): `.ideaprobe/user-profile.md`
- Saved reports (user data): `.ideaprobe/reports/`

When the user mentions a business idea, asks "is this worth building", wants to
compare ideas or scope an MVP, load the matching IdeaProbe skill **before**
answering and follow it exactly (structured scores out of 100, cited evidence,
GO / EXPLORE / PIVOT / STOP verdict).

## Persistence in cloud sessions

Cloud containers are ephemeral: files that are not committed and pushed are lost
when the session ends.
- After creating or changing `.ideaprobe/user-profile.md`, tell the user it only
  persists if committed, and offer to commit and push it. Warn first if the
  repository may be public — the profile contains personal information.
- After presenting a final report (validation, comparison, research, MVP spec),
  offer to save it as `.ideaprobe/reports/YYYY-MM-DD-<idea-slug>-<report-type>.md`
  (exactly the template output plus the data sources), and offer to commit it.

{router_body.strip()}
{END}
"""


def build(target: Path) -> list[str]:
    agents = sorted(p.stem for p in (ROOT / "agents").glob("*.md"))
    version = json.loads((ROOT / ".claude-plugin/plugin.json").read_text())["version"]
    written: list[str] = []

    def write(rel: str, content: str) -> None:
        path = target / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        written.append(rel)

    # Clean previously generated files so removed sources do not linger.
    manifest_path = target / BUNDLE_DIR / "manifest.json"
    if manifest_path.exists():
        for rel in json.loads(manifest_path.read_text()).get("files", []):
            p = target / rel
            if p.is_file():
                p.unlink()
                if p.parent.name != "skills" and p.name == "SKILL.md" and not any(p.parent.iterdir()):
                    p.parent.rmdir()

    for skill_file in sorted((ROOT / "skills").glob("*/SKILL.md")):
        name = skill_file.parent.name
        fm, body = split_frontmatter(skill_file.read_text())
        body = transform(body, agents)
        used = [a for a in agents if re.search(rf"`{re.escape(a)}`|\"{re.escape(a)}\"", body)]
        if used:
            body = body.rstrip("\n") + "\n" + dispatch_note(used)
        header = f"\n<!-- Generated from skills/{name}/SKILL.md by scripts/build-project-local.py. Edit the source, then rebuild. -->\n"
        write(f".claude/skills/{name}/SKILL.md", fm + header + body)

    for agent_file in sorted((ROOT / "agents").glob("*.md")):
        fm, body = split_frontmatter(agent_file.read_text())
        body = transform(body, agents)
        if agent_file.stem != "validation-reviewer":
            body = body.rstrip("\n") + "\n" + AGENT_WEB_NOTE
        header = f"\n<!-- Generated from agents/{agent_file.name} by scripts/build-project-local.py. Edit the source, then rebuild. -->\n"
        write(f".claude/agents/{agent_file.name}", fm + header + body)

    for ref in sorted((ROOT / "refs").glob("*.md")):
        write(f"{REFS_PREFIX}{ref.name}", transform(ref.read_text(), agents))

    # CLAUDE.md bootstrap replaces the plugin's SessionStart hook.
    _, router = split_frontmatter((ROOT / "skills/using-ideaprobe/SKILL.md").read_text())
    block = bootstrap_block(transform(router, agents), version)
    claude_md = target / "CLAUDE.md"
    existing = claude_md.read_text() if claude_md.exists() else ""
    if BEGIN in existing and END in existing:
        pre, rest = existing.split(BEGIN, 1)
        post = rest.split(END, 1)[1].lstrip("\n")
        new = pre + block + ("\n" + post if post else "")
    else:
        new = (existing.rstrip("\n") + "\n\n" if existing.strip() else "") + block
    claude_md.write_text(new)

    manifest = {
        "name": "ideaprobe",
        "version": version,
        "source": "https://github.com/j7an/ideaprobe",
        "generator": "scripts/build-project-local.py",
        "files": sorted(written),
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    return written


def check() -> int:
    """Build into a temp copy and compare with the committed bundle in this repo."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        if (ROOT / "CLAUDE.md").exists():
            shutil.copy(ROOT / "CLAUDE.md", tmp_path / "CLAUDE.md")
        files = build(tmp_path) + [f"{BUNDLE_DIR}/manifest.json", "CLAUDE.md"]
        stale = [
            rel
            for rel in files
            if not (ROOT / rel).exists() or (ROOT / rel).read_text() != (tmp_path / rel).read_text()
        ]
    if stale:
        print("Project-local bundle is stale. Run: python3 scripts/build-project-local.py")
        for rel in stale:
            print(f"  {rel}")
        return 1
    print("Project-local bundle is up to date.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--target", type=Path, default=ROOT, help="project directory to install into")
    parser.add_argument("--check", action="store_true", help="verify the committed bundle is up to date")
    args = parser.parse_args()
    if args.check:
        return check()
    target = args.target.resolve()
    if not target.is_dir():
        print(f"Target directory does not exist: {target}", file=sys.stderr)
        return 1
    written = build(target)
    print(f"Installed IdeaProbe project-local bundle into {target} ({len(written)} files + manifest, CLAUDE.md)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
